import numpy as np
from mpi4py import MPI
from petsc4py import PETSc
from slepc4py import SLEPc
import ufl
from dolfinx import fem, io, mesh, plot
from dolfinx.fem.petsc import LinearProblem
from dolfinx.io import gmsh as gmshio
import gmsh

class Solver_wire:

    def __init__(self, Lx: float = 20.0, Ly: float = 4.0, h: float = 0.2, 
                 geometry_type: str = "straight", nev: int = 20):
        """
        Parameters:
          Lx: Length of the wire along the x-axis
          Ly: Width of the wire along the y-axis
          h:  Target mesh size element length (crucial for your convergence loops)
          geometry_type: Either "straight" or "constricted"
          nev: Number of requested eigenvalues
        """
        self.Lx = Lx
        self.Ly = Ly
        self.h = h
        self.geometry_type = geometry_type
        self.nev = nev

        # Build mesh via Gmsh, function space, BCs, and forms on construction
        self.msh, self.facet_tags = self._make_mesh()
        self.V                    = fem.functionspace(self.msh, ("Lagrange", 1))
        self.bc, self.bc_dofs     = self._boundary_conditions()
        self.a_form, self.m_form  = self._variational_forms()

    # ── Mesh Generation (Gmsh API) ──────────────────────────────────────────
    def _make_mesh(self):
        """
        Programmatically builds either a straight channel or a constricted channel 
        using the OpenCASCADE kernel in Gmsh, tagging boundaries automatically.
        """
        gmsh.initialize()
        gmsh.option.setNumber("General.Terminal", 0)  # Suppress console noise
        
        model = gmsh.model
        model.add("quantum_wire")
        
        # Coordinates bounding our wire
        x_min, x_max = -self.Lx / 2.0, self.Lx / 2.0
        y_min, y_max = -self.Ly / 2.0, self.Ly / 2.0
        
        if self.geometry_type == "straight":
            # Variant A: Simple rectangular channel
            rect = model.occ.addRectangle(x_min, y_min, 0, self.Lx, self.Ly)
            model.occ.synchronize()
            
        elif self.geometry_type == "constricted":
            # Variant B: Waveguide with an internal scattering bottleneck at x=0
            main_channel = model.occ.addRectangle(x_min, y_min, 0, self.Lx, self.Ly)
            
            # Define dimensions for top and bottom notch cuts
            w_cut = self.Ly * 0.30  # Width of the constriction zone
            h_cut = self.Ly * 0.35  # How deep the constriction squeezes in from top/bottom
            
            cut_top = model.occ.addRectangle(-w_cut/2, y_max - h_cut, 0, w_cut, h_cut)
            cut_bot = model.occ.addRectangle(-w_cut/2, y_min, 0, w_cut, h_cut)
            
            # Boolean subtraction to create the physical bottleneck channel
            model.occ.cut([(2, main_channel)], [(2, cut_top), (2, cut_bot)])
            model.occ.synchronize()
        else:
            raise ValueError(f"Unknown geometry_type: {self.geometry_type}")
            
        # 1. Tag the 2D domain surface (Physical Group 1)
        surfaces = model.getEntities(dim=2)
        model.addPhysicalGroup(2, [surfaces[0][1]], tag=1)
        
        # 2. Tag all outer boundary edges (Physical Group 2 for Dirichlet walls)
        boundaries = model.getBoundary(surfaces, oriented=False)
        boundary_ids = [b[1] for b in boundaries]
        model.addPhysicalGroup(1, boundary_ids, tag=2)
        
        # Enforce global mesh sizing tracking the parameter 'h'
        gmsh.option.setNumber("Mesh.MeshSizeMax", self.h)
        gmsh.option.setNumber("Mesh.MeshSizeMin", self.h)
        
        # Generate the 2D triangular mesh
        model.mesh.generate(2)
        
        # Direct pipeline conversion from Gmsh into FEniCSx structures
        msh_data = gmshio.model_to_mesh(
            model, MPI.COMM_WORLD, rank=0, gdim=2
        )
        # Use read_from_msh (which reads from a saved .msh file on disk):
        # msh, _, facet_tags = io.gmshio.read_from_msh(
        #     "wire.msh", MPI.COMM_WORLD, rank=0, gdim=2
        # )
        gmsh.finalize()
        return msh_data[0], msh_data[2]

    # ── Boundary conditions (Using Facet Tags) ───────────────────────────────
    def _boundary_conditions(self):
        """
        Uses the boundary facet tags generated by Gmsh to cleanly locate boundary DOFs.
        """
        tdim = self.msh.topology.dim
        self.msh.topology.create_connectivity(tdim - 1, tdim)
        
        # Find the facets associated with Physical Group Tag 2 (our exterior boundaries)
        boundary_facets = self.facet_tags.find(2)
        
        boundary_dofs = fem.locate_dofs_topological(
            self.V, tdim - 1, boundary_facets
        )
        bc = fem.dirichletbc(
            PETSc.ScalarType(0.0), boundary_dofs, self.V
        )
        return bc, boundary_dofs

    # ── Variational forms ─────────────────────────────────────────────────────
    def _variational_forms(self):
        """
        Weak formulation of the quantum particle in a box (-0.5 * laplacian(u) = E * u).
        """
        V_pot = 0.0  # Free propagation inside the wire boundaries
        
        u = ufl.TrialFunction(self.V)
        v = ufl.TestFunction(self.V)

        a = (0.5 * ufl.dot(ufl.grad(u), ufl.grad(v)) + V_pot * u * v) * ufl.dx
        m = u * v * ufl.dx

        return fem.form(a), fem.form(m)

    # ── Assemble ──────────────────────────────────────────────────────────────
    def assemble(self):
        A = fem.petsc.assemble_matrix(self.a_form, bcs=[self.bc])
        A.assemble()

        M = fem.petsc.assemble_matrix(self.m_form, bcs=[self.bc])
        M.assemble()

        # Eliminate boundary DOFs from mass matrix to prevent spurious modes
        bc_dofs = np.asarray(self.bc_dofs, dtype=PETSc.IntType)
        diag    = M.getDiagonal()
        diag.setValues(bc_dofs, np.zeros(bc_dofs.size, dtype=PETSc.ScalarType))
        diag.assemble()
        M.setDiagonal(diag)
        M.assemblyBegin()
        M.assemblyEnd()

        return A, M

    # ── Solve ─────────────────────────────────────────────────────────────────
    def solve(self, A, M):
        eps = SLEPc.EPS().create(MPI.COMM_WORLD)
        eps.setOperators(A, M)
        eps.setProblemType(SLEPc.EPS.ProblemType.GHEP)
        eps.setWhichEigenpairs(SLEPc.EPS.Which.TARGET_REAL)
        eps.setTarget(0.0)
        eps.setDimensions(nev=self.nev)

        st = eps.getST()
        st.setType(SLEPc.ST.Type.SINVERT)   

        eps.setFromOptions()
        eps.solve()

        n_conv = eps.getConverged()
        print(f"[{self.geometry_type.upper()} WIRE] Converged eigenvalues: {n_conv}")

        energies = []
        eigvecs  = []
        for i in range(min(self.nev, n_conv)):
            vr, vi = A.createVecs()
            lam = eps.getEigenpair(i, vr, vi)
            energies.append(lam.real)
            # Use .array.copy() for secure petsc4py memory copying
            eigvecs.append(vr.array.copy())

        return np.array(energies), np.array(eigvecs)